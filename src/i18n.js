function swapWords(lang, text) {
  let out = text;
  LEX.forEach(([es, ptText, enText]) => {
    const next = lang === 'pt' ? ptText : enText;
    out = out.replace(new RegExp(es, 'ig'), next);
  });
  return out;
}

export function detectLanguage() {
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'es').toLowerCase();
  if (nav.startsWith('pt')) return 'pt';
  if (nav.startsWith('en')) return 'en';
  return 'es';
}

export function translate(lang, key, vars) {
  const table = ui[lang] || ui.es;
  let value = table[key] ?? ui.es[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, item]) => {
      value = value.replaceAll(`{${name}}`, String(item));
    });
  }
  return value;
}

export function translateContent(lang, value) {
  if (value == null) return '';
  const text = String(value);
  if (!lang || lang === 'es') return text;
  if (phrases[text]?.[lang]) return phrases[text][lang];
  const swapped = swapWords(lang, text);
  return swapped;
}

export function greetingKey(date = new Date()) {
  const hour = date.getHours();
  if (hour < 12) return 'greet.morning';
  if (hour < 19) return 'greet.afternoon';
  return 'greet.evening';
}
