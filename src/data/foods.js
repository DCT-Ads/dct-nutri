export function findFood(id) {
  return foods.find((food) => food.id === id);
}

export function describeMeal(text) {
  const chunks = String(text || '')
    .split(/,|\s+e\s+|\s+y\s+|\s+and\s+|\s+com\s+|\s+with\s+|\+/i)
    .map((part) => part.trim())
    .filter(Boolean);
  const found = [];
  const used = new Set();
  chunks.forEach((chunk) => {
    const qtyMatch = chunk.match(/(\d+(?:[.,]\d+)?)/);
    const qty = qtyMatch ? Math.min(8, Math.max(0.5, Number(qtyMatch[1].replace(',', '.')))) : 1;
    const blob = chunk.toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu, '');
    let best = null;
    let bestLen = 0;
    foods.forEach((food) => {
      [food.name, ...(food.aliases || [])].forEach((alias) => {
        const key = alias.toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu, '');
        if (key.length >= 3 && blob.includes(key) && key.length > bestLen) {
          best = food;
          bestLen = key.length;
        }
      });
    });
    if (best && !used.has(best.id)) {
      used.add(best.id);
      found.push({ ...best, qty });
    }
  });
  return found;
}

export function searchFoods(query) {
  const q = String(query || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .trim();
  if (!q) return foods;
  return foods.filter((food) => {
    const blob = [food.name, ...(food.aliases || [])].join(' ').toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu, '');
    return blob.includes(q);
  });
}
